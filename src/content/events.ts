export function isAcquisitionEventUnlocked(
  event: AcquisitionEventDefinition,
  fame: number,
  networkSchools: number,
) {
  return !event.requiresSecretUpgrade &&
    event.unlockMembers <= fame &&
    (event.requiredNetworkSchools ?? 0) <= networkSchools;
}

export function getUnlockedAcquisitionEvents(fame: number, networkSchools = 0) {
  return ACQUISITION_EVENTS.filter((event) => isAcquisitionEventUnlocked(event, fame, networkSchools));
}

export function getAcquisitionEventDefinition(id: AcquisitionEventId) {
  return ACQUISITION_EVENTS.find((event) => event.id === id);
}
